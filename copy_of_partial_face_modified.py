import cv2
import numpy as np
import tensorflow as tf
from tensorflow.keras.models import load_model
from tensorflow.keras.applications import MobileNetV2
from tensorflow.keras.preprocessing.image import img_to_array
import imutils

# Load the pre-trained Partial Face Recognition model
model = load_model("partial_face_model.h5")
# Ensure you have this trained model

# Load MobileNetV2 for feature extraction
mobilenet = MobileNetV2(weights="imagenet", include_top=False, input_shape=(128, 128, 3))

# Load Haar cascade for face detection
face_cascade = cv2.CascadeClassifier(cv2.data.haarcascades + "haarcascade_frontalface_default.xml")

# Connect to CCTV (Replace URL with your CCTV RTSP/HTTP stream or use 0 for webcam)
cctv_url = "rtsp://username:password@cctv_ip:port/stream"
cap = cv2.VideoCapture(cctv_url)

# Function to preprocess image for MobileNetV2
def preprocess_face(face):
    face = cv2.resize(face, (224, 224))
    face = img_to_array(face)
    face = np.expand_dims(face, axis=0)
    face = face / 255.0  # Normalize
    return face

# Real-time CCTV Partial Face Recognition
while True:
    ret, frame = cap.read()
    if not ret:
        print("Failed to grab frame. Check CCTV stream.")
        break

    frame = imutils.resize(frame, width=800)
    gray = cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY)
    faces = face_cascade.detectMultiScale(gray, scaleFactor=1.1, minNeighbors=5, minSize=(60, 60))

    for (x, y, w, h) in faces:
        face_roi = frame[y:y+h, x:x+w]
        processed_face = preprocess_face(face_roi)

        # Extract features using MobileNetV2
        features = mobilenet.predict(processed_face)
        features = features.reshape(1, -1)  # Flatten for LSTM input

        # Predict identity
        prediction = model.predict(features)
        label = "Unknown"
        confidence = np.max(prediction) * 100

        # Assign label based on confidence threshold
        if confidence > 80:
            label = f"Person {np.argmax(prediction)}"

        # Draw bounding box and label
        cv2.rectangle(frame, (x, y), (x+w, y+h), (0, 255, 0), 2)
        cv2.putText(frame, f"{label}: {confidence:.2f}%", (x, y - 10),
                    cv2.FONT_HERSHEY_SIMPLEX, 0.6, (0, 255, 0), 2)

    # Display CCTV feed with recognition
    cv2.imshow("CCTV Partial Face Recognition", frame)

    if cv2.waitKey(1) & 0xFF == ord("q"):  # Press 'q' to quit
        break

cap.release()
cv2.destroyAllWindows()