def show_prediction(test_image_path, model, face_db):
    # Load the test image
    test_image = cv2.imread(test_image_path)
    if test_image is None:
        print("❌ Image could not be loaded. Check the file path.")
        return

    test_image_rgb = cv2.cvtColor(test_image, cv2.COLOR_BGR2RGB)
    test_image_resized = cv2.resize(test_image_rgb, (160, 160))
    test_image_resized = np.expand_dims(test_image_resized, axis=0)

    # Get embedding
    test_embedding = model.embeddings(test_image_resized)

    # Find closest match
    min_dist = float("inf")
    best_match = None
    best_match_image = None

    for img_path, stored_embedding in face_db.items():
        dist = np.linalg.norm(test_embedding - stored_embedding)
        if dist < min_dist:
            min_dist = dist
            best_match = img_path
            best_match_image = cv2.imread(best_match)

    if best_match_image is None:
        print("❌ No match found.")
        return

    best_match_image_rgb = cv2.cvtColor(best_match_image, cv2.COLOR_BGR2RGB)

    # Show images
    fig, axes = plt.subplots(1, 2, figsize=(10, 5))

    axes[0].imshow(test_image_rgb)
    axes[0].set_title("Input Image")
    axes[0].axis("off")

    axes[1].imshow(best_match_image_rgb)
    axes[1].set_title(f"Recognized as: {best_match.split('/')[-2]}")
    axes[1].axis("off")

    plt.show()

