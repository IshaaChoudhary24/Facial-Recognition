face_db = {}

# Function to Extract Face Embeddings
def get_embedding(image_path):
    image = cv2.imread(image_path)
    image = cv2.cvtColor(image, cv2.COLOR_BGR2RGB)
    image = cv2.resize(image, (160, 160))  # FaceNet requires 160x160 images
    image = np.expand_dims(image, axis=0)
    embedding = embedder.embeddings(image)
    return embedding[0]  # 128D feature vector

# Extract embeddings for all images
for person in os.listdir(dataset_path):
    person_path = os.path.join(dataset_path, person)
    if os.path.isdir(person_path):
        for image in os.listdir(person_path):
            img_path = os.path.join(person_path, image)
            face_db[img_path] = get_embedding(img_path)

print(f"✅ Stored {len(face_db)} face embeddings.")

def recognize_face(test_img_path):
    test_embedding = get_embedding(test_img_path)
    min_distance = float("inf")
    best_match = None

    for img_path, emb in face_db.items():
        distance = cosine(test_embedding, emb)  # Cosine similarity
        if distance < min_distance:
            min_distance = distance
            best_match = img_path

    print(f"✅ Closest match: {best_match} (Cosine Distance: {min_distance:.4f})")

